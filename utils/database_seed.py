def get_fiber_data(fiber_name: str) -> dict:
    """Returns deeply nested dictionary of specific environmental factors."""
    return FIBER_SUSTAINABILITY_METRICS.get(fiber_name)

def get_chemical_limit(chem_name: str, standard="zdhc_mrsl_v3_limit_ppm") -> float:
    """Retrieve standard specific threshold limits."""
    data = CHEMICAL_COMPLIANCE_LIMITS.get(chem_name)
    return data.get(standard) if data else None

def get_chemical_data(chem_name: str) -> dict:
    """Retrieve full toxicological profile of a chemical."""
    return CHEMICAL_COMPLIANCE_LIMITS.get(chem_name)

def list_all_fibers() -> list:
    """Return list of all 150+ valid fiber strings."""
    return list(FIBER_SUSTAINABILITY_METRICS.keys())

def list_all_chemicals() -> list:
    """Return list of all MRSL mapped chemicals."""
    return list(CHEMICAL_COMPLIANCE_LIMITS.keys())
